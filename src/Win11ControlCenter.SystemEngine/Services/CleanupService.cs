using Win11ControlCenter.Core.Enums;
using Win11ControlCenter.Core.Interfaces;
using Win11ControlCenter.Core.Models;
using Win11ControlCenter.SystemEngine.Handlers;

namespace Win11ControlCenter.SystemEngine.Services;

public class CleanupService : ICleanupService
{
    private readonly ILoggingService _logger;
    private readonly IOperationExecutor _operationExecutor;

    public CleanupService(ILoggingService logger, IOperationExecutor operationExecutor)
    {
        _logger = logger;
        _operationExecutor = operationExecutor;
    }

    public async Task<IReadOnlyList<CleanupTarget>> ScanCleanupTargetsAsync(CancellationToken cancellationToken = default)
    {
        return await Task.Run(() =>
        {
            var targets = GetCatalogTargets();

            foreach (var target in targets)
            {
                cancellationToken.ThrowIfCancellationRequested();

                if (target.TargetPath.Equals("RecycleBin", StringComparison.OrdinalIgnoreCase))
                {
                    var (bytes, count) = CleanupOperationHandler.QueryRecycleBin();
                    target.TotalSizeBytes = bytes;
                    target.FileCount = count;
                    continue;
                }

                if (!Directory.Exists(target.TargetPath))
                {
                    target.TotalSizeBytes = 0;
                    target.FileCount = 0;
                    continue;
                }

                long totalBytes = 0;
                int totalFiles = 0;

                try
                {
                    var searchPattern = target.ExcludedPatterns.FirstOrDefault() ?? "*";
                    var dir = new DirectoryInfo(target.TargetPath);

                    foreach (var file in dir.EnumerateFiles(searchPattern, SearchOption.AllDirectories))
                    {
                        try
                        {
                            totalBytes += file.Length;
                            totalFiles++;
                        }
                        catch
                        {
                            // Inaccessible or locked file in scan
                        }
                    }
                }
                catch (Exception ex)
                {
                    _logger.LogWarning($"Permission limited during scan of '{target.TargetPath}': {ex.Message}", "CleanupScan");
                }

                target.TotalSizeBytes = totalBytes;
                target.FileCount = totalFiles;
            }

            _logger.LogInfo($"Cleanup scan completed for {targets.Count} targets.", "CleanupService");
            return (IReadOnlyList<CleanupTarget>)targets;
        }, cancellationToken);
    }

    public async Task<OperationPlan> CreateCleanupPlanAsync(IEnumerable<CleanupTarget> targets, bool isDryRun)
    {
        var requestedItems = new List<OperationItem>();

        foreach (var target in targets)
        {
            var pattern = target.ExcludedPatterns.FirstOrDefault() ?? "*";

            var item = new OperationItem
            {
                Name = target.Name,
                Description = target.Description,
                Category = "Storage Cleanup",
                RiskLevel = target.RiskLevel,
                OperationType = OperationType.FileCleanup,
                Reversibility = ReversibilityTier.Irreversible,
                Target = target.TargetPath,
                RequiresAdmin = target.RequiresAdmin,
                RollbackSupported = false,
                Metadata = new Dictionary<string, string>
                {
                    { "SearchPattern", pattern },
                    { "TargetId", target.Id }
                }
            };

            requestedItems.Add(item);
        }

        return await _operationExecutor.GeneratePlanAsync(requestedItems, "System Storage Cleanup", isDryRun);
    }

    public static List<CleanupTarget> GetCatalogTargets()
    {
        var winDir = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
        var localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);

        return new List<CleanupTarget>
        {
            new()
            {
                Id = "user-temp",
                Name = "User Temporary Files",
                Description = "Temporary working files generated by applications in your user profile.",
                TargetPath = Path.GetTempPath().TrimEnd('\\'),
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = false,
                IsSelected = true
            },
            new()
            {
                Id = "windows-temp",
                Name = "Windows System Temporary Files",
                Description = "System-level temporary files created by Windows services and installers.",
                TargetPath = Path.Combine(winDir, "Temp"),
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = true,
                IsSelected = true
            },
            new()
            {
                Id = "recycle-bin",
                Name = "Windows Recycle Bin",
                Description = "Permanently removes all deleted files held in the system Recycle Bin.",
                TargetPath = "RecycleBin",
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = false,
                IsSelected = true
            },
            new()
            {
                Id = "explorer-thumbnails",
                Name = "File Explorer Thumbnail Cache",
                Description = "Cached image and document thumbnail databases that will be rebuilt on demand.",
                TargetPath = Path.Combine(localAppData, @"Microsoft\Windows\Explorer"),
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = false,
                IsSelected = true,
                ExcludedPatterns = new List<string> { "thumbcache_*.db" }
            },
            new()
            {
                Id = "crash-dumps",
                Name = "Application Crash Dumps",
                Description = "Post-mortem memory dump files stored after previous application crashes.",
                TargetPath = Path.Combine(localAppData, "CrashDumps"),
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = false,
                IsSelected = true
            },
            new()
            {
                Id = "delivery-optimization",
                Name = "Delivery Optimization Cache",
                Description = "Downloaded peer-to-peer Windows Update cache files that are no longer needed.",
                TargetPath = Path.Combine(winDir, @"SoftwareDistribution\DeliveryOptimization"),
                RiskLevel = OperationRiskLevel.Safe,
                RequiresAdmin = true,
                IsSelected = true
            }
        };
    }
}

